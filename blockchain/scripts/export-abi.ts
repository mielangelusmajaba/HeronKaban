/**
 * Writes the compiled ABIs into the Next.js app as a typed TS module
 * (src/lib/chain/abi.ts), so the app never imports from blockchain/ directly.
 * Run after `hardhat build`: `npm run export-abi`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = (name: string) =>
  JSON.parse(readFileSync(new URL(`artifacts/contracts/${name}.sol/${name}.json`, root), "utf8")).abi;

const out = fileURLToPath(new URL("../src/lib/chain/abi.ts", root));
const body = `// GENERATED by blockchain/scripts/export-abi.ts. Do not edit by hand.
export const pesoTokenAbi = ${JSON.stringify(read("PesoToken"), null, 2)} as const;

export const heronTreasuryAbi = ${JSON.stringify(read("HeronTreasury"), null, 2)} as const;
`;
writeFileSync(out, body);
console.log(`Wrote ${out}`);
